package Model.World.enums;

/**
 * This enum class defines possible values for elevation
 * Level:
 * 0 - UNDERSEA: deep ocean
 * 1 - SURFACE: sea-level terrain (sea or coast)
 * 2 - TERRA: flat land
 * 3 - ELEVATED: hills, higher mountains, plateau, etc.
 * 4 - IMPASSABLE: high mountain ranges
 */
public enum Elevation {
    UNDERSEA, SURFACE, TERRA, ELEVATED, IMPASSABLE
}
